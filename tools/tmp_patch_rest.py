import io, re

def patch(path, pairs, regexes=()):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    for old, new in pairs:
        assert old in s, f'{path} NOT FOUND: {old[:60]}'
        s = s.replace(old, new, 1)
    for pat, rep, cnt in regexes:
        s2, n = re.subn(pat, rep, s, count=cnt, flags=re.S)
        assert n == cnt, f'{path} regex failed: {pat[:50]} (n={n})'
        s = s2
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    print('ok', path, len(s))


