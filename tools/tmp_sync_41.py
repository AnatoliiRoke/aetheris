import io

def replace_line(path, prefix, new_text):
    s = io.open(path, encoding='utf-8').read()
    i = s.index(prefix)
    j = s.index('\n', i)
    s = s[:i] + new_text + s[j:]
    io.open(path, 'w', encoding='utf-8').write(s)
    print('ok', path)


