import io

def patch(path, pairs):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    for old, new in pairs:
        assert old in s, f'{path} NOT FOUND: {old[:70]}'
        s = s.replace(old, new, 1)
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    print('ok', path, len(s))


