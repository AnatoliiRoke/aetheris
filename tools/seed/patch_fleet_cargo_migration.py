#!/usr/bin/env python3
"""Adds the cargo entities to the migration designer and the model snapshot of the fleet module.

The files are generated by the Entity Framework, but the tooling is not run here: the blocks are
inserted in the same shape the generator writes, so the next migration that the tooling makes
continues from the same model.
"""

import pathlib
import sys

SNAPSHOT = pathlib.Path("server/src/Aetheris.Fleet/Data/Migrations/FleetDbContextModelSnapshot.cs")
DESIGNER = pathlib.Path("server/src/Aetheris.Fleet/Data/Migrations/20261110152000_FleetCargo.Designer.cs")

ENTITY_BLOCK = '''
            modelBuilder.Entity("Aetheris.Fleet.Data.Entities.{entity}", b =>
                {{
                    b.Property<long>("Id")
                        .ValueGeneratedOnAdd()
                        .HasColumnType("bigint")
                        .HasColumnName("id");

                    NpgsqlPropertyBuilderExtensions.UseIdentityByDefaultColumn(b.Property<long>("Id"));

                    b.Property<long>("Amount")
                        .HasColumnType("bigint")
                        .HasColumnName("amount");

                    b.Property<int>("ResourceId")
                        .HasColumnType("integer")
                        .HasColumnName("resource_id");

                    b.Property<long>("{owner_column}")
                        .HasColumnType("bigint")
                        .HasColumnName("{owner_column_snake}");

                    b.Property<DateTimeOffset>("UpdatedAt")
                        .HasColumnType("timestamp with time zone")
                        .HasColumnName("updated_at");

                    b.HasKey("Id")
                        .HasName("pk_{table}");

                    b.HasIndex("{owner_column}")
                        .HasDatabaseName("ix_{table}_{owner_column_snake}");

                    b.HasIndex("{owner_column}", "ResourceId")
                        .IsUnique()
                        .HasDatabaseName("ix_{table}_{owner_column_snake}_resource_id");

                    b.ToTable("{table}", null, t =>
                        {{
                            t.HasCheckConstraint("ck_{table}_amount", "amount >= 0");
                        }});
                }});
'''

RELATION_BLOCK = '''
            modelBuilder.Entity("Aetheris.Fleet.Data.Entities.{entity}", b =>
                {{
                    b.HasOne("Aetheris.Fleet.Data.Entities.{owner}", null)
                        .WithMany()
                        .HasForeignKey("{owner_column}")
                        .OnDelete(DeleteBehavior.Cascade)
                        .IsRequired()
                        .HasConstraintName("fk_{table}_{owner_table}_{owner_column_snake}");
                }});
'''

ENTITIES = [
    {
        "entity": "FleetCargoEntity",
        "table": "fleet_cargo",
        "owner": "FleetEntity",
        "owner_table": "fleet",
        "owner_column": "FleetId",
        "owner_column_snake": "fleet_id",
    },
    {
        "entity": "ShipCargoEntity",
        "table": "ship_cargo",
        "owner": "ShipEntity",
        "owner_table": "ship",
        "owner_column": "ShipId",
        "owner_column_snake": "ship_id",
    },
]

ANCHORS = {
    "FleetCargoEntity": '            modelBuilder.Entity("Aetheris.Fleet.Data.Entities.FleetEntity", b =>',
    "ShipCargoEntity": '            modelBuilder.Entity("Aetheris.Fleet.Data.Entities.ShipCostEntity", b =>',
}

# The relations live in their own section at the end of the file: the first block of it is the one
# that names a foreign key.
RELATION_ANCHOR = '            modelBuilder.Entity("Aetheris.Fleet.Data.Entities.FleetShipEntity", b =>\n                {\n                    b.HasOne('


def insert_before(text: str, anchor: str, block: str) -> str:
    index = text.index(anchor)

    return text[:index] + block + text[index:]


def patch(path: pathlib.Path) -> None:
    text = path.read_text(encoding="utf-8")

    if "FleetCargoEntity" in text:
        print(f"{path.name}: already patched")

        return

    # The blocks are inserted before the entity they come before in the alphabetical order, so the
    # file keeps the shape the generator writes.
    for entity in ENTITIES:
        text = insert_before(text, ANCHORS[entity["entity"]], ENTITY_BLOCK.format(**entity))

    for entity in ENTITIES:
        text = insert_before(text, RELATION_ANCHOR, RELATION_BLOCK.format(**entity))

    path.write_text(text, encoding="utf-8")
    print(f"{path.name}: patched")


def main() -> int:
    if not SNAPSHOT.exists():
        print("The snapshot of the fleet module is missing.")

        return 1

    patch(SNAPSHOT)

    if not DESIGNER.exists():
        print("The designer of the migration is missing.")

        return 1

    patch(DESIGNER)

    return 0


if __name__ == "__main__":
    sys.exit(main())
