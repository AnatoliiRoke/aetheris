#!/usr/bin/env python3
"""Adds the mass of a nebula to the migration designer and the model snapshot of the world module.

The files are generated by the Entity Framework, but the tooling is not run here: the properties
are inserted in the same shape the generator writes, so the next migration that the tooling makes
continues from the same model.
"""

import pathlib
import sys

SNAPSHOT = pathlib.Path("server/src/Aetheris.World/Data/Migrations/WorldDbContextModelSnapshot.cs")
DESIGNER = pathlib.Path("server/src/Aetheris.World/Data/Migrations/20261110153000_NebulaMass.Designer.cs")

PROPERTY_BLOCK = '''
                    b.Property<long>("InitialMass")
                        .HasColumnType("bigint")
                        .HasColumnName("initial_mass");

                    b.Property<long>("Mass")
                        .HasColumnType("bigint")
                        .HasColumnName("mass");
'''

# The block of the table ends with the line that names it; the properties go before the key.
ANCHOR = '''                    b.HasKey("Id")
                        .HasName("pk_nebula");
'''

TABLE_BLOCK = '''                    b.ToTable("nebula", null, t =>
                        {
                            t.HasCheckConstraint("ck_nebula_mass", "mass >= 0");
                        });
'''


def insert_before(text: str, anchor: str, block: str) -> str:
    index = text.index(anchor)

    return text[:index] + block + text[index:]


def patch(path: pathlib.Path) -> None:
    text = path.read_text(encoding="utf-8")

    # The asteroid field has a mass of its own, so the check looks at the table of the nebula.
    if 'b.ToTable("nebula", null, t =>' in text:
        print(f"{path.name}: already patched")

        return

    text = insert_before(text, ANCHOR, PROPERTY_BLOCK)

    old_table = '                    b.ToTable("nebula", (string)null);\n'

    if old_table not in text:
        print(f"{path.name}: the table line is not found.")

        return

    text = text.replace(old_table, TABLE_BLOCK, 1)
    path.write_text(text, encoding="utf-8")
    print(f"{path.name}: patched")


def main() -> int:
    if not SNAPSHOT.exists():
        print("The snapshot of the world module is missing.")

        return 1

    patch(SNAPSHOT)

    if not DESIGNER.exists():
        print("The designer of the migration is missing.")

        return 1

    patch(DESIGNER)

    return 0


if __name__ == "__main__":
    sys.exit(main())
