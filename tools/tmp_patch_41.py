import io, re

PATH = 'documentation/tasks/00041-modeliuvannia-korabliv.md'

with io.open(PATH, encoding='utf-8') as f:
    s = f.read()

def sub(pattern, rep, count=1):
    global s
    s2, n = re.subn(pattern, rep, s, count=count, flags=re.S)
    assert n == count, f'failed: {pattern[:50]} (n={n})'
    s = s2

sub(r'4\. \*\*Час складання\*\* — за розміром проєкту \(кількість слотів, маса\) так, щоб легкий корабель збивався близько \*\*10 хвилин\*\*, а найважчий — не більше \*\*6 годин\*\*\.',
    '4. **Час складання** — **залежить від розміру корабля** (кількість слотів, маса) так, щоб легкий корабель збивався близько **10 хвилин**, а найважчий — не більше **6 годин**. Залежність має бути монотонною: більший проєкт — довше.')

sub(r'(\*\*Вхідні дані\*\* \(уже є в сиді\):\n- корпуси: [^\n]*\n)',
    '\\1- **вимога «рівень верфі» на корпус** — щоб модель знала, який корпус на якому рівні верфі відкривається (запис у сиді через спільний механізм вимог 00011);\n')

sub(r'4\. Час складання потрапляє у діапазон \*\*10 хв — 6 год\*\* для всіх корпусів\.',
    '4. Час складання потрапляє у діапазон **10 хв — 6 год** для всіх корпусів і **монотонно залежить від розміру корабля**: більший проєкт — довше.')

with io.open(PATH, 'w', encoding='utf-8') as f:
    f.write(s)

print('ok 41', len(s))
