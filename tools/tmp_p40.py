import io

PATH = 'documentation/tasks/00040-formuvannia-flotiv.md'
s = io.open(PATH, encoding='utf-8').read()

# 1) рішення 9 — після пункту 9
m = '9. **Готові кораблі на ринку не продаються** (модулі й компоненти — продаються).'
i = s.index(m)
j = s.index('\n', i)
s = s[:j] + """
10. **Планети не втрачаються** (рішення автора, 04.11.2026): корабель, що стояв на планеті, **не зникає** разом із нею. Тому в складі гравця може бути корабель без планети — куди він переходить, за автором (див. відкриті питання).""" + s[j:]

# 2) джерела — додати речення про планети, що не втрачаються
m2 = '- **Кораблі, екіпаж і деталі — з планети**, де стоять; переміщення флоту між планетами — окрема задача (перельоти).'
i = s.index(m2)
j = s.index('\n', i)
s = s[:j] + ' **Планети не втратаються**, тож корабель може лишитися без планети — правило переходу за автором.' + s[j:]

# 3) додати корабель до флоту
m3 = '  - **додати корабель до флоту**: корабель стоїть на планеті, він не в іншому флоті, обмеження розміру флоту не перевищено;'
assert m3 in s, 'm3'
s = s.replace(m3, m3 + ' корабель без планети теж можна додати — обмеження лише те, що він не в іншому флоті;', 1)

# 4) відкрите питання
i = s.index('4. ❓ **Перенесення флоту між планетами**')
j = s.index('\n', i)
s = s[:j] + """
4а. ❓ **Корабель без планети** (планета зникла): залишається «осиротілим», переходить до флоту, чи переноситься на іншу планету цивілізації — за автором.""" + s[j:]

io.open(PATH, 'w', encoding='utf-8').write(s)
print('ok 40', len(s))
