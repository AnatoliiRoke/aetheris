import io

PATH = 'documentation/tasks/00041-modeliuvannia-korabliv.md'
s = io.open(PATH, encoding='utf-8').read()

def replace_line(prefix, new_text):
    global s
    i = s.index(prefix)
    j = s.index('\n', i)
    s = s[:i] + new_text + s[j:]


# 1) правило про приналежність модулів до корпусів — у рішеннях
replace_line('2. **Приклади комплектації — орієнтир, а не рішення**:',
"""2. **Приклади комплектації — орієнтир, а не рішення**: бойовий легкий — 2 двигуни, реактор, 2 гармати, 2 блоки броні, можливо слот щита; транспорт — 2 двигуни, генератор, 3–4 блоки контейнеру; копалка — один слот під бур.
2а. **Модулі мають приналежність до корпусів** (рішення автора, 04.11.2026): не тільки кількість слотів. Найбільший реактор не можна поставити на легкий транспорт. Приналежність — це **конкретне найменування** (перелік корпусів, до яких модуль придатний), а не «клас» чи «вага». У документах це вже є: [перелік 3 з 6](../references/perelik-3-moduli.md), відкрите питання 3 — «Розкладка модулів по корпусах: окрема сторінка вибору, яку підготує агент»; [перелік 4 з 6](../references/perelik-4-korpusy.md) — правило «тип корпусу це лише розмір і вмістимість, спеціалізацію створює гравець модулями».""")

# 2) у моделі: мінімальна комплектація — враховує приналежність
replace_line('1. **Мінімальна життєздатна комплектація** —',
'1. **Мінімальна життєздатна комплектація** — найдешевший набір модулів, придатних саме цьому корпусу (приналежність до корпусів), за якого корабель може полетіти й стріляти: двигун, реактор, живтєзабезпечення, мінімальна зброя, мінімальний боєкомплект, трюм під цей боєкомплект.')

# 3) у моделі: утримання корабля
replace_line('6. **Перевірка балансу**:',
"""6. **Утримання корабля** — окрема стаття (14 §2.6): `утримання/год = Σ (утримання_корпусу + Σ утримання_модулів)`. Щойно корабель вироблено, на нього **автоматично нараховується утримання** кредитами. Числа теж моделюються: щоб утримання було узгоджене з вартістю складання й не забивало гравця в мінус.
7. **Перевірка балансу**:""")

# 4) вихід моделі — звіт
replace_line('### 3.2. Вивід',
"""### 3.2. Вивід

Звіт — **таблиця у репозиторії** (Markdown-файл у `documentation/backlog/`, наприклад `modeluvannia-korabliv.md`), бо його треба читати й порівнювати з часом. Форма звіту:
| Корпус | Мінімальна комплектація | Слотів | Трюм | Час складання | Вартість | Утримання/год |""")

# 5) сценарії — приналежність
replace_line('**Сценарії перебору** (задає автор):',
'**Сценарії перебору** (задає автор; кожен сценарій має бути реалістичний з погляду приналежності модулів до корпусів):')

# 6) критерії
replace_line('2. Для кожного корпуса визначено: мінімальна комплектація, кількість слотів, місткість базового трюма, час складання, вартість.',
'2. Для кожного корпуса визначено: мінімальна комплектація, кількість слотів, місткість базового трюма, час складання, вартість, утримання за годину.')

# 7) відкриті питання
i = s.index('## 6. Відкриті питання')
j = s.index('## 7. Результат виконання')
new_q = """## 6. Відкриті питання

1. ✅ **Сценарії перебору** — це проблема гравця, як він проєктує: модель має дати числа, а гравець сам вирішує, що йому потрібно. Конкретний перелік типових комплектацій — за автором.
2. ✅ **Утримання корабля** — окрема стаття (14 §2.6); нараховується автоматично щойно корабель вироблено; числа моделюються разом із вартістю складання.
3. ✅ **Форма звіту** — таблиця у репозиторії (Markdown у `documentation/backlog/`), щоб читати й порівнювати версії балансу.
4. ✅ **Кому належать звіти** — файл у репозиторії разом із кодом моделі; історія прогонів — теж у репозиторії, окремим файлом на прогін, щоб бачити, як числа змінювалися.

Лишилося невизначеним:
- ❓ **Приналежність модулів до корпусів**: автор сказав, що це «десь є в документах», і це справді відкрите питання 3 переліку 3 з 6 («Розкладка модулів по корпусах: окрема сторінка вибору, яку підготує агент»). Питання: хто її готує — автор чи агент? Без неї модель не може порахувати мінімальну комплектацію для кожного корпуса.
- ❓ **Де брати дані про утримання**: у сиді характеристик «утримання» для корпусів і модулів зараз немає (є лише формула в 14 §2.6) — їх треба додати в модель/сид, числа — за автором або з моделювання.

"""
s = s[:i] + new_q + s[j:]

io.open(PATH, 'w', encoding='utf-8').write(s)
